import Foundation

public struct PCMWave: Identifiable {
    public let id: Int
    public let name: String
    public var displayName: String { "\(id). \(name)" }
    
    public init(id: Int, name: String) {
        self.id = id
        self.name = name
    }
}

public struct PCMCategory: Identifiable, Hashable {
    public let id: String
    public let name: String
    public let waves: [PCMWave]
    
    public init(id: String, name: String, waves: [PCMWave]) {
        self.id = id
        self.name = name
        self.waves = waves
    }

    public static func == (lhs: PCMCategory, rhs: PCMCategory) -> Bool {
            lhs.id == rhs.id
        }
        
        public func hash(into hasher: inout Hasher) {
            hasher.combine(id)
        }
}

