import SwiftUI

struct ThemeColors {
    static let background = Color(red: 0.1, green: 0.1, blue: 0.12)
    static let secondaryBackground = Color(red: 0.15, green: 0.15, blue: 0.17)
    static let accent = Color.blue
    static let text = Color.white
    static let secondaryText = Color.gray
    
    static let tabSelected = Color(red: 0.2, green: 0.2, blue: 0.22)
    static let tabUnselected = Color(red: 0.15, green: 0.15, blue: 0.17)
}

struct ThemeMetrics {
    static let cornerRadius: CGFloat = 8
    static let padding: CGFloat = 12
    static let spacing: CGFloat = 8
}
